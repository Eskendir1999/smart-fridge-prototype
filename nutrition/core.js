function exclusionStems(word){
  const w = String(word||'').toLowerCase().trim();
  const preset = EXCLUSION_PRESETS.find(x => x.word === w);
  if(preset) return preset.stems;
  // грубая основа слова: «кинза» → «кинз», «баклажаны» → «баклажан»
  let stem = w.replace(/[^a-zа-яё0-9 -]/gi,'').trim();
  while(stem.length > 4 && /[аеёиоуыэюяйь]$/.test(stem)) stem = stem.slice(0,-1);
  return stem.length >= 3 ? [stem] : [];
}
function profileWords(profile){
  const v = profile && profile.meal_choices && profile.meal_choices._exclude;
  return Array.isArray(v) ? v.filter(x => typeof x === 'string' && x.trim()).slice(0, 12) : [];
}
function dishText(dish){
  const parts = [dish.title, dish.desc, ...(dish.items || []), ...(dish.need || []).map(n => n.n)];
  return (' ' + parts.filter(Boolean).join(' ') + ' ').toLowerCase();
}

