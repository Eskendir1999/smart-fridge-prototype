const SFDiet = (() => {
  const isBF = p => !!p && p.sex === 'female' && p.diet_mode === 'breastfeeding';
  const babyAge = p => { const v = p && p.baby_age_months; return v == null || v === '' || isNaN(Number(v)) ? null : Number(v); };
  const exclusions = p => Array.isArray(p && p.excluded_foods) ? p.excluded_foods.filter(x => x in EXCLUSION_LABELS) : [];
  const words = p => { const v = p && p.meal_choices && p.meal_choices._exclude; return Array.isArray(v) ? v.filter(x => typeof x === 'string' && x.trim()).slice(0, 12) : []; };
  function bmr(sex, w, h, age){ const base = 10*w + 6.25*h - 5*age; return sex === 'male' ? base + 5 : base - 161; }
  function kcal(p, w){
    const tdee = bmr(p.sex, w, Number(p.height_cm), Number(p.age)) * ({low:1.2, moderate:1.375, high:1.55}[p.activity_level] || 1.375);
    if(isBF(p)){
      const a = babyAge(p); const need = tdee + (a != null && a >= 6 ? 400 : 330);
      return p.goal !== 'lose' ? Math.round(need) : Math.max(Math.round(need - 300), 1800);
    }
    if(p.goal !== 'lose') return Math.round(tdee);
    const floor = Number(p.age) < 18 ? 1400 : (p.sex === 'male' ? 1500 : 1200);
    return Math.max(Math.round(tdee - 500), floor);
  }
  function blockReason(dish, p){
    const hit = (dish.tags || []).filter(t => exclusions(p).includes(t));
    if(hit.length) return 'Исключено: ' + hit.map(t => EXCLUSION_LABELS[t]).join(', ');
    const ws = words(p);
    if(ws.length){ const text = dishText(dish); const w = ws.find(x => exclusionStems(x).some(st => text.includes(st))); if(w) return 'Исключено: ' + w; }
    if(isBF(p) && dish.bf === 'avoid') return dish.bfNote || 'Не рекомендуется при грудном вскармливании';
    return null;
  }
  const allowed = (slot, p) => DISHES.filter(x => x.slot === slot && !blockReason(x, p));
  function slots(d, p){ const bf = isBF(p); if(d === 7 && !bf) return ['f']; return bf ? ['b','s','l','d'] : ['b','l','d']; }
  function defaultId(d, slot, p){
    if(slot === 's') return SNACK_ROTATION[(d-1) % SNACK_ROTATION.length];
    if(d === 7 && isBF(p)) return BF_DAY7[slot];
    return PROGRAM_DAYS[d][slot];
  }
  function resolve(d, slot, p, choices){
    const defId = defaultId(d, slot, p);
    const chosen = ((choices || {})[d] || {})[slot];
    const dish = DISH_BY_ID[chosen] || DISH_BY_ID[defId];
    if(!blockReason(dish, p)) return dish;
    const alts = allowed(slot, p);
    return alts.length ? alts[(d-1) % alts.length] : dish;
  }
  function week(p){
    const choices = p && p.meal_choices && typeof p.meal_choices === 'object' ? p.meal_choices : {};
    const out = [];
    for(let d = 1; d <= 7; d++) out.push({d, slots: slots(d, p).map(slot => ({slot, dish: resolve(d, slot, p, choices)}))});
    return out;
  }
  const norm = s => String(s || '').toLowerCase().replace(/ё/g, 'е');
  function missing(p, inventory){
    const byKey = new Map();
    week(p).forEach(({slots}) => slots.forEach(({dish}) => (dish.need || []).forEach(n => { if(!byKey.has(n.k)) byKey.set(n.k, {name:n.n, keyword:n.k}); })));
    const all = [...byKey.values()].concat(DAILY_NEEDS);
    return all.filter(x => !inventory.some(name => norm(name).includes(norm(x.keyword))));
  }
  function portion(dish, ratio){
    return dish.portion ? Math.round(dish.portion*ratio) + ' г белка' : dish.portionMl ? Math.round(dish.portionMl*ratio) + ' мл салата' : '';
  }
  return {isBF, babyAge, kcal, blockReason, week, missing, portion, SLOT_META};
})();
